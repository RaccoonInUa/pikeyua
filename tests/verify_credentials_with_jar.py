#!/usr/bin/env python3
"""Real-JAR cross-language regression; all state is temporary and synthetic."""
import contextlib
import importlib.util
import io
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('credential_cli_integration', ROOT / 'scripts/pikeyua-credentials.py')
cli = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = cli
spec.loader.exec_module(cli)


class OfflineService:
    """Only the service boundary is mocked. Storage and Java are real."""
    def initially_active(self): return False
    def stop(self): pass
    def require_stopped(self): pass
    def start(self): raise AssertionError('Must not start any daemon')


def main():
    if len(sys.argv) != 2:
        raise SystemExit('Usage: python3 tests/verify_credentials_with_jar.py /path/to/pikeyua.jar')
    jar = Path(sys.argv[1]).resolve(strict=True)
    with tempfile.TemporaryDirectory(prefix='pikeyua-admin-test-') as name:
        root = Path(name)
        root.chmod(0o700)
        classes = root / 'classes'; classes.mkdir()
        state_dir = root / 'state'; state_dir.mkdir(mode=0o700)
        subprocess.run(['javac', '-cp', str(jar), '-d', str(classes),
                        str(ROOT / 'tests/java/AdminStateFixture.java')], check=True)
        java = ['java', '-cp', str(classes) + os.pathsep + str(jar), 'AdminStateFixture']
        subprocess.run(java + ['create', str(state_dir)], check=True)
        store = cli.StateFile(state_dir / 'config.json', owner=os.geteuid())
        original = store.load()
        marker = store.marker.read_bytes()
        records = original.document['credentials']
        # Project metadata only; none of the private/PIN fields are serialized.
        projection = json.dumps([cli.public_record(c) for c in records])
        for c in records:
            assert c['keyPair']['privateKey'] not in projection
        assert original.document['pinHash'] not in projection
        assert store.path.read_bytes() == original.raw
        # Exercise the same transaction function used by the CLI, with only
        # systemd mocked. The on-disk JSON was generated by the actual JAR.
        with contextlib.redirect_stdout(io.StringIO()):
            cli.delete_one(store, OfflineService(), cli.credential_id(records[0]), lambda _: True)
        changed = store.load()
        expected = original.document.copy()
        expected['credentials'] = records[1:]
        assert changed.document == expected
        assert store.marker.read_bytes() == marker
        subprocess.run(java + ['verify', str(state_dir)], check=True)
        print('PASS: Python administrator CLI interoperates with actual V7.3 state across independent JVMs')


if __name__ == '__main__':
    main()
